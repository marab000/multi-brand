/** Слот по product_type или null, если товар не для конструктора */
export function slotOfProductType(productType: string | null | undefined): PodborSlot | null {
  if (!productType) return null;
  const t = productType.trim().toLowerCase();
  for (const slot of SLOT_ORDER) {
    if ((SLOT_TYPES[slot] as readonly string[]).some((s) => s.toLowerCase() === t)) {
      return slot;
    }
  }
  return null;
}
